# ---------- Проверка второго слоя (ИИ) на контрольном наборе ----------
# Работает, только если в окружении заданы YANDEX_API_KEY и YANDEX_FOLDER_ID.

def main_llm():
    import asyncio

    from app import llm
    from app.config import settings

    if not settings.llm_enabled:
        print("\nИИ-слой: ключ YandexGPT не задан, проверка пропущена.")
        return

    async def flags(text):
        g = await llm.guard_check(text)
        return g

    async def run():
        print("\nКОНТРОЛЬНЫЙ НАБОР: код + ИИ-проверка\n")
        for name, items, want in [("Кризис", CRISIS_2, "help"), ("«Мне плохо»", DISTRESS_2, "help"),
                                  ("Атаки", ATTACK_2, "attack"), ("Обычные", NORMAL_2, "none")]:
            hit = 0
            for t in items:
                g = await flags(t)
                helped = any_help(t) or g["crisis"]
                attacked = detect_attack(t) or g["attack"]
                if want == "help" and helped:
                    hit += 1
                elif want == "attack" and attacked:
                    hit += 1
                elif want == "none" and (helped or attacked):
                    hit += 1
            label = "ложных срабатываний" if want == "none" else "распознано"
            print(f"{name}: {label} {hit}/{len(items)}")

    asyncio.run(run())


if __name__ == "__main__":
    main_llm()
