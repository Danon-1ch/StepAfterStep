"""Фильтры безопасности чат-бота «Шаг за шагом».

Здесь собрана, наверное, самая важная часть всего бота. Нейросеть можно
попробовать «уговорить», а обычный код нельзя, поэтому всё, от чего зависит
безопасность человека, я вынес сюда, в программные проверки:

1. detect_crisis   – признаки угрозы жизни во входящем сообщении;
1б. detect_distress – просьба о помощи вроде «мне плохо», «не справляюсь»;
2. detect_attack   – попытка обойти правила бота или запросить что-то вредное;
3. check_bot_reply – проверка ответа нейросети перед тем, как его увидит человек.

Если подключён YandexGPT, поверх этих правил работает ещё и проверка смысла
моделью (llm.guard_check). Но даже если модель не ответила или ошиблась,
решение «показывать карточку помощи или нет» этот модуль может принять сам.
"""
import re


# ---------- подготовка текста ----------

def normalize(text: str) -> str:
    """Приводит сообщение к одному виду, чтобы правила не зависели от того,
    как человек пишет: с большой буквы или нет, через «ё» или «е»,
    с тремя восклицательными знаками или вообще без знаков.
    """
    text = text.lower().replace("ё", "е")
    text = re.sub(r"[^\w\s]", " ", text)     # знаки препинания превращаем в пробелы
    return re.sub(r"\s+", " ", text).strip()  # лишние пробелы схлопываем в один


# ---------- 1. кризис: угроза жизни ----------
# Шаблоны написаны под то, как обычно пишут в мессенджерах: коротко,
# без знаков препинания, разговорными словами. Важно, что тут не слова, а куски фраз:
# одно слово «умереть» встречается и в «умираю от скуки», а это не кризис.

CRISIS_PATTERNS = [
    # мысли о суициде
    r"покончить с собой", r"покончу с собой", r"убить себя", r"убью себя",
    # «(больше |уже )?» – необязательное слово: ловит и «не хочу жить»,
    # и «не хочу больше жить». Без этого фильтр пропускал вторую фразу.
    r"не хочу (больше |уже )?жить", r"не хочется (больше |уже )?жить",
    r"устал жить", r"уйти из жизни", r"заснуть и не проснуться",
    r"уснуть и не проснуться", r"меня (скоро )?не будет", r"это конец",
    r"жить не хочу", r"незачем жить", r"нет смысла жить", r"не вижу смысла",
    r"хочу умереть", r"лучше бы я умер", r"лучше бы меня не было",
    r"суицид", r"самоубийств", r"повешусь", r"повеситься",
    r"вскрыть вены", r"вскрою вены", r"спрыгнуть с", r"прыгнуть с крыши",
    r"выпрыгнуть из окна", r"покончить со всем", r"всем прощайте", r"прощайте все",
    # передозировка и опасное физическое состояние.
    # «передоз» без окончания – так ловятся и «передоз», и «передозировка»
    r"передоз", r"наглотал", r"выпил все таблетки", r"выпила все таблетки",
    r"не могу дышать", r"(трудно|тяжело) дышать", r"теряю сознание", r"судорог",
    r"белая горячка", r"белочка", r"вижу то чего нет", r"слышу голоса",
    r"сильно болит сердце", r"сердце останавливается",
    # угроза другим людям (например, родственник пишет о пьяном муже)
    r"хочу убить", r"убью его", r"убью ее",
]
# Все шаблоны склеиваются в одно большое регулярное выражение через «|» (ИЛИ)
# и компилируются один раз при запуске сервера, а не на каждое сообщение.
_crisis_re = re.compile("|".join(CRISIS_PATTERNS))


def detect_crisis(text: str) -> bool:
    return bool(_crisis_re.search(normalize(text)))


# ---------- 1б. человеку плохо (просьба о помощи) ----------
# Это не обязательно угроза жизни, но карточку с телефонами бот показывает сразу.
# Логика простая: если человек ошибся и ему «не настолько плохо», он просто
# закроет карточку. Если ошибся фильтр и не показал её – цена ошибки выше.

DISTRESS_PATTERNS = [
    # (?! спал) – «негативный просмотр вперёд»: шаблон НЕ срабатывает, если дальше
    # идёт «спал». Так «мне плохо» считается просьбой о помощи,
    # а «мне плохо спалось» – нет. Это был реальный ложный сигнал на испытании.
    r"мне (очень |совсем |так |сильно |реально |правда )?"
    r"(плохо|хреново|херово|паршиво|тяжело|страшно|худо)(?! спал)",
    r"плохо себя чувствую", r"чувствую себя (очень |совсем )?плохо",
    # то же самое: «нужна помощь» – да, «нужна помощь с выбором группы» – нет
    r"помогите", r"помоги мне", r"спасите", r"нужна помощь(?! с )",
    r"\bsos\b",  # \b – граница слова, чтобы не срабатывало внутри других слов
    r"не справляюсь", r"не вывожу", r"не выдерживаю", r"больше не могу",
    r"сил (больше )?нет", r"ломка", r"меня ломает", r"на грани", r"меня накрыло",
    r"схожу с ума", r"сейчас сорвусь", r"кроет", r"паническ", r"паника",
    r"меня трясет",  # «трясёт» тоже поймается: normalize заменил «ё» на «е»
]
_distress_re = re.compile("|".join(DISTRESS_PATTERNS))


def detect_distress(text: str) -> bool:
    return bool(_distress_re.search(normalize(text)))


# ---------- 2. атаки и вредные запросы ----------
# Попытки «взломать» бота обычно однотипные: попросить забыть инструкции,
# сыграть другую роль, включить какой-то особый режим. Плюс отдельно – вопросы,
# которые помогают употреблению. На них бот отвечает отказом в любом случае.

ATTACK_PATTERNS = [
    # попытки сменить правила или роль
    r"игнорируй", r"игнорировать (все )?(инструкц|правил)",
    r"забудь (все |свои |эти )?(инструкц|правил|ограничен)",
    r"обойди", r"обход(и|ить)? (ограничен|правил|фильтр)",
    r"без ограничений", r"без цензуры", r"отключи (фильтр|ограничен|цензур)",
    r"режим разработчика", r"developer mode", r"jailbreak",
    r"\bdan\b",  # «DAN» (Do Anything Now) – известный приём обхода ограничений
    r"с этого момента ты", r"теперь ты будешь", r"притворись", r"представь что ты не",
    r"системн\w* (промпт|инструкц)", r"system prompt", r"покажи (свои |твои )?инструкц",
    r"твои инструкции", r"ignore (all|previous|the)", r"act as", r"новые правила",
    r"(нет|без) правил", r"как будто ты не",
    r"рецепт (как )?(сварить|приготовить|меф|винт)",
    # вредные запросы про употребление
    r"где (купить|достать|взять) (нарк|меф|герыч|героин|соль|спайс|траву|дозу)",
    r"как (достать|купить|сварить|приготовить) (нарк|меф|героин|спайс|соль)",
    r"закладк", r"сколько (можно|нужно) (выпить|принять|употребить)",
    r"какая доза", r"дозировк", r"как (скрыть|спрятать) (запах|употребление)",
]
_attack_re = re.compile("|".join(ATTACK_PATTERNS))


def detect_attack(text: str) -> bool:
    return bool(_attack_re.search(normalize(text)))


# ---------- 3. проверка ответа бота ----------
# Последний рубеж. Даже если человек как-то обманул первые два слоя,
# готовый ответ нейросети проверяется ещё раз, и опасный ответ просто
# не дойдёт до экрана. Получается, что «уговаривать» пришлось бы две разные
# проверки, и вторая сам разговор вообще не видит.

FORBIDDEN_IN_REPLY = [
    r"\d+\s?(мг|мл|миллиграмм|грамм|таблет)",  # любые дозы: «50 мг», «2 таблетки»
    r"дозировк", r"закладк",
    r"можно (немного |чуть )?(выпить|употребить)",
    r"выпей\b", r"употреби\b", r"прими (таблетк|лекарств)",
    # бот не врач, диагнозы ставить не должен
    r"ставлю (вам |тебе )?диагноз",
    r"у (тебя|вас) (алкоголизм|наркомания|депрессия|шизофрения)",
    # и не должен оскорблять, даже если модель вдруг «сорвётся»
    r"ты (слабак|ничтожество|безнадежен)",
]
_forbidden_re = re.compile("|".join(FORBIDDEN_IN_REPLY))


def check_bot_reply(text: str) -> bool:
    """True – ответ безопасен, False – ответ нужно заменить."""
    if not text or not text.strip():
        return False  # пустой ответ тоже считаем плохим: человек не должен остаться без ответа
    return not _forbidden_re.search(normalize(text))


# ---------- готовые ответы ----------
# В опасных ситуациях бот отвечает не нейросетью, а заранее написанным текстом.
# Так ответ всегда предсказуем, и в нём точно нет ничего лишнего.

ATTACK_REPLY = (
    "Я могу говорить только о поддержке и выздоровлении — правила моей роли не меняются. "
    "И я не подскажу ничего об употреблении. Давай лучше о тебе: как ты сейчас, что происходит?"
)

UNSAFE_REPLY_FALLBACK = (
    "Я хочу ответить аккуратно, поэтому скажу просто: я рядом и слышу тебя. "
    "Расскажи, что ты чувствуешь прямо сейчас? Если становится совсем тяжело — "
    "можно сразу позвонить по номерам из кнопки «Мне плохо»."
)

DISTRESS_REPLY = (
    "Слышу, что тебе сейчас плохо, и я рядом. Если есть угроза жизни или здоровью — "
    "не жди, звони прямо сейчас, номера ниже. А если можешь — расскажи мне, что происходит?"
)

